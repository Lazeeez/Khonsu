using FrameList = std::vector<std::pair<FrameType, std::vector<std::byte>>>;

class OracleSource {
public:
  virtual ~OracleSource() = default;
  // Returns nullopt when the oracle cannot serve the request (replay divergence).
  virtual std::optional<LlmResponse> llm(std::uint16_t actor, const LlmRequest& req, bool& cached) = 0;
  FrameList frames;  // frames to append to the log for this step
  std::vector<std::uint16_t> frame_actors;
};

namespace {

std::vector<std::byte> encode_request(const Digest128& h, const LlmRequest& req) {
  Writer w;
  w.digest(h).str(req.role).varint(req.sample).str(req.prompt);
  return w.bytes();
}

std::vector<std::byte> encode_response(const Digest128& h, const LlmResponse& r, bool cached) {
  Writer w;
  w.digest(h).u8(cached ? 1 : 0).varint(r.latency_us).varint(r.prompt_tokens).varint(r.completion_tokens).str(r.text);
  return w.bytes();
}

struct DecodedResponse {
  Digest128 hash;
  bool cached = false;
  LlmResponse r;
};

std::optional<DecodedResponse> decode_response(std::span<const std::byte> p) {
  Reader rd(p);
  DecodedResponse d;
  d.hash = rd.digest();
  d.cached = rd.u8() != 0;
  d.r.latency_us = rd.varint();
  d.r.prompt_tokens = static_cast<std::uint32_t>(rd.varint());
  d.r.completion_tokens = static_cast<std::uint32_t>(rd.varint());
  d.r.text = std::string(rd.str());
  if (!rd.ok()) return std::nullopt;
  return d;
}

}  // namespace

class LiveOracle final : public OracleSource {
public:
  explicit LiveOracle(Kernel& k) : k_(k) {}
  std::optional<LlmResponse> llm(std::uint16_t actor, const LlmRequest& req, bool& cached) override {
    const Digest128 h = req.hash();
    frames.emplace_back(FrameType::OracleRequest, encode_request(h, req));
    frame_actors.push_back(actor);
    LlmResponse r;
    if (const auto it = k_.cache_.find(h); it != k_.cache_.end()) {
      r = it->second;
      cached = true;
    } else {
      r = k_.model_->complete(req, k_.entropy_.next());  // the nondeterministic call
      k_.cache_.emplace(h, r);
      cached = false;
    }
    frames.emplace_back(FrameType::OracleResponse, encode_response(h, r, cached));
    frame_actors.push_back(actor);
    return r;
  }

private:
  Kernel& k_;
};

class ReplayOracle final : public OracleSource {
public:
  ReplayOracle(const EventLog& log, std::uint64_t begin, std::uint64_t end) : log_(log), cur_(begin), end_(end) {}

  std::optional<LlmResponse> llm(std::uint16_t actor, const LlmRequest& req, bool& cached) override {
    const auto rq = next(FrameType::OracleRequest);
    const auto rs = rq ? next(FrameType::OracleResponse) : std::nullopt;
    if (!rq || !rs) {
      if (error.empty()) error = "agent issued an oracle call that is not in the recording";
      return std::nullopt;
    }
    Reader rd(log_.frame(*rq).payload);
    const Digest128 recorded = rd.digest();
    if (recorded != req.hash()) {
      error = "oracle request hash mismatch: agent asked " + req.hash().short_hex() + ", recording has " +
              recorded.short_hex();
      return std::nullopt;
    }
    const auto d = decode_response(log_.frame(*rs).payload);
    if (!d || d->hash != recorded) {
      error = "malformed oracle response frame";
      return std::nullopt;
    }
    for (const auto lsn : {*rq, *rs}) {
      const auto f = log_.frame(lsn);
      frames.emplace_back(f.header.type, std::vector<std::byte>(f.payload.begin(), f.payload.end()));
      frame_actors.push_back(actor);
    }
    cached = d->cached;
    responses.emplace_back(recorded, d->r);
    return d->r;
  }

  [[nodiscard]] bool exhausted() {
    return !next(FrameType::OracleRequest).has_value();
  }

  std::string error;
  std::vector<std::pair<Digest128, LlmResponse>> responses;

private:
  std::optional<std::uint64_t> next(FrameType want) {
    while (cur_ < end_) {
      const auto t = log_.frame(cur_).header.type;
      if (t == want) return cur_++;
      if (t == FrameType::OracleRequest || t == FrameType::OracleResponse) return std::nullopt;  // peek only
      ++cur_;
    }
    return std::nullopt;
  }
  const EventLog& log_;
  std::uint64_t cur_, end_;
};

// ==========================================================================================
// Step context: what a reducer sees. All effects are buffered, then committed atomically.
// ==========================================================================================

struct StepCtx {
  Kernel& k;
  NodeStore& s;
  NodeRef root;
  std::uint64_t now;
  std::uint32_t step;
  std::uint64_t sample;
  OracleSource& oracle;
  Kernel::StepOutput& o;
  Event ev;
  std::vector<Event> out;
  bool diverged = false;

  [[nodiscard]] std::string get(std::string_view key) const {
    const auto t = s.get_text(root, key);
    return t ? std::string(*t) : std::string();
  }
  void put(std::string_view key, std::string_view text) { root = s.put_text(root, key, text); }
  [[nodiscard]] std::string file(std::string_view path) const { return s.read_file(root, path).value_or(""); }
  void write(std::string_view path, std::string_view contents) { root = s.put_file(root, path, contents); }

  void send(std::uint16_t to, std::string topic, std::string body, std::uint64_t delay = kMsgLatencyUs) {
    out.push_back(Event{now + delay, 0, to, ev.to, EventKind::Msg, std::move(topic), std::move(body)});
  }

  void llm(std::string role, std::string prompt) {
    LlmRequest req{role, std::move(prompt), sample};
    bool cached = false;
    const auto r = oracle.llm(ev.to, req, cached);
    if (!r) {
      diverged = true;
      return;
    }
    const std::uint32_t tokens = r->prompt_tokens + r->completion_tokens;
    o.tokens += tokens;
    o.llm_calls += 1;
    if (cached) {
      o.tokens_saved += tokens;
      o.cache_hits += 1;
    }
    put("sys/tokens", std::to_string(to_u64(get("sys/tokens")) + tokens));
    out.push_back(Event{now + r->latency_us, 0, ev.to, ev.to, EventKind::LlmReply, role, r->text});
    o.spans.push_back(Span{ev.to, SpanKind::Llm, cached, step, now, now + r->latency_us, "llm · " + role});
  }

  // Tools run inside the kernel against the timeline's own VFS, so they are
  // deterministic functions of state and need no recording.
  void tool(std::string name) {
    std::string result;
    std::uint64_t gas = 0;
    if (name == "run_tests") {
      const std::string api = file(kApiPath), user = file(kUserPath), client = file(kClientPath);
      gas = api.size() + user.size() + client.size();
      const auto exports = exported_functions(api);
      auto exported = [&](std::string_view fn) { return std::find(exports.begin(), exports.end(), fn) != exports.end(); };
      const bool has_fn = user.find("export async function getUserName") != std::string::npos;
      std::string missing;
      for (const auto& c : api_calls(user))
        if (!exported(c)) missing = c;
      const bool calls_ok = has_fn && missing.empty() && !api_calls(user).empty();
      std::string lookup;
      if (const auto p = client.find(kPatchMarker); p != std::string::npos)
        lookup = trim(std::string_view(client).substr(p + kPatchMarker.size(), kPatchWidth));
      const bool registry_ok = exported(lookup);
      const bool pass = has_fn && calls_ok && registry_ok;
      result = pass ? "PASS  test/user.test.ts (3 tests)\n" : "FAIL  test/user.test.ts\n";
      result += std::string(has_fn ? "  ✓" : "  ✗") + " exports getUserName\n";
      result += std::string(calls_ok ? "  ✓" : "  ✗") + " returns the display name\n";
      if (!missing.empty())
        result += "      TypeError: api." + missing + " is not a function\n        at getUserName (src/user.ts:5:26)\n";
      result += std::string(registry_ok ? "  ✓" : "  ✗") + " client registers USER_LOOKUP_FN\n";
      if (!registry_ok) result += "      Error: USER_LOOKUP_FN \"" + lookup + "\" is not exported by src/api.ts\n";
    } else {
      result = "error: unknown tool " + name;
    }
    const std::uint64_t latency = 600'000 + gas * 4;
    out.push_back(Event{now + latency, 0, ev.to, ev.to, EventKind::ToolReply, name, result});
    o.spans.push_back(Span{ev.to, SpanKind::Tool, false, step, now, now + latency, "sandbox · " + name});
    put("sys/gas", std::to_string(to_u64(get("sys/gas")) + gas));
  }
};

