void Kernel::prune(std::uint32_t tid) { tl(tid).pruned = true; }

std::size_t Kernel::gc() {
  const auto t0 = Clock::now();
  std::vector<NodeRef> roots;
  for (auto& t : timelines_) {
    for (std::size_t i = 0; i < t->steps.size(); ++i) {
      auto& s = t->steps[i];
      // Pruned timelines keep only their base and head; intermediate history is released.
      if (t->pruned && i != 0 && i + 1 != t->steps.size()) s.root = kEmpty;
      if (!s.root.empty()) roots.push_back(s.root);
    }
  }
  const std::size_t freed = store_.collect(roots);
  metrics_.last_gc_ms = us_since(t0) / 1000.0;
  metrics_.last_gc_freed = freed;
  return freed;
}

