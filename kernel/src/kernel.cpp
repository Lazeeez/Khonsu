std::vector<std::string> exported_functions(std::string_view src) {
  std::vector<std::string> out;
  constexpr std::string_view kw = "export async function ";
  for (auto p = src.find(kw); p != std::string_view::npos; p = src.find(kw, p + 1)) {
    auto b = p + kw.size();
    auto e = b;
    while (e < src.size() && is_ident(src[e])) ++e;
    out.emplace_back(src.substr(b, e - b));
  }
  return out;
}

std::vector<std::string> api_calls(std::string_view src) {
  std::vector<std::string> out;
  for (auto p = src.find("api."); p != std::string_view::npos; p = src.find("api.", p + 1)) {
    auto b = p + 4;
    auto e = b;
    while (e < src.size() && is_ident(src[e])) ++e;
    if (e < src.size() && src[e] == '(') out.emplace_back(src.substr(b, e - b));
  }
  return out;
}

