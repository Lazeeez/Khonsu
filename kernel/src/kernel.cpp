namespace {
std::string coder_prompt(const StepCtx& c, std::uint64_t attempt) {
  std::string p = "ROLE coder\nTASK\n" + c.get("@coder/task");
  if (const auto notes = c.get("@coder/notes"); !notes.empty()) p += "\nNOTES\n" + notes;
  p += "\nFILE src/user.ts\n" + c.file(kUserPath);
  if (const auto f = c.get("@coder/last_failure"); !f.empty()) p += "\nLAST TEST RUN\n" + f;
  p += "\nATTEMPT " + std::to_string(attempt);
  return p;
}
}  // namespace

void Kernel::dispatch(StepCtx& c) {
  const Event& ev = c.ev;
  const std::string who(actor_name(ev.to));
  auto& o = c.o;

  if (ev.kind == EventKind::Restart) {
    c.put("@" + who + "/status", "alive");
    o.label = "supervisor restarted " + who + " from its last committed state";
    o.tag = "restart";
    return;
  }

  switch (ev.to) {
    case kPlanner:
      if (ev.kind == EventKind::Start) {
        std::vector<std::string> paths;
        store_.for_each(c.root, [&](std::string_view k, NodeRef v) {
          if (v.tag() == Tag::File) paths.emplace_back(k);
        });
        std::sort(paths.begin(), paths.end());
        std::string files;
        for (const auto& p : paths) files += p + "\n";
        c.llm("planner", "ROLE planner\nISSUE\n" + c.file(kIssuePath) + "\nFILES\n" + files);
        o.label = "planner → LLM: draft a plan for issue #42";
      } else if (ev.kind == EventKind::LlmReply) {
        c.put("@planner/plan", ev.body);
        if (ev.body.find("[route: research]") != std::string::npos) {
          c.send(kResearcher, "research", ev.body);
          o.label = "planner: plan routes through the researcher";
          o.tag = "plan_research";
        } else {
          c.send(kCoder, "task", ev.body);
          o.label = "planner: plan goes straight to the coder (skips the docs)";
          o.tag = "plan_direct";
        }
      }
      break;

    case kResearcher:
      if (ev.kind == EventKind::Msg) {
        c.llm("researcher", "ROLE researcher\nSummarize the API the coder needs.\nDOCS\n" + c.file(kDocsPath));
        o.label = "researcher reads docs/API.md → LLM: summarize";
      } else if (ev.kind == EventKind::LlmReply) {
        c.put("@researcher/notes", ev.body);
        c.send(kCoder, "task", c.get("@planner/plan") + "\n" + ev.body);
        o.label = "researcher → coder: API notes";
      }
      break;

    case kCoder:
      if (ev.kind == EventKind::Msg && ev.topic == "task") {
        c.put("@coder/task", ev.body);
        c.put("@coder/attempts", "0");
        c.llm("coder", coder_prompt(c, 1));
        o.label = "coder → LLM: implement getUserName (attempt 1)";
      } else if (ev.kind == EventKind::Msg && ev.topic == "fix") {
        c.put("@coder/last_failure", ev.body);
        const auto attempts = to_u64(c.get("@coder/attempts"));
        if (attempts >= kMaxAttempts) {
          c.send(kReviewer, "escalate", ev.body);
          o.label = "coder gives up after " + std::to_string(attempts) + " attempts → reviewer";
        } else {
          c.llm("coder", coder_prompt(c, attempts + 1));
          o.label = "coder → LLM: fix failing test (attempt " + std::to_string(attempts + 1) + ")";
        }
      } else if (ev.kind == EventKind::LlmReply) {
        const std::string& t = ev.body;
        const auto fb = t.find("FILE src/user.ts\n");
        const auto ep = t.find("ENDPOINT ");
        std::string code = fb != std::string::npos && ep != std::string::npos
                               ? t.substr(fb + 17, ep - (fb + 17))
                               : std::string(kUserStub);
        std::string fn = ep != std::string::npos ? trim(t.substr(ep + 9, t.find('\n', ep) - (ep + 9))) : "";
        c.write(kUserPath, code);
        std::string client = c.file(kClientPath);
        if (const auto p = client.find(kPatchMarker); p != std::string::npos) {
          client.replace(p + kPatchMarker.size(), kPatchWidth, pad(fn, kPatchWidth));  // in-place, one page
          c.write(kClientPath, client);
        }
        c.put("@coder/attempts", std::to_string(to_u64(c.get("@coder/attempts")) + 1));
        c.send(kTester, "verify", "src/user.ts");
        o.label = "coder writes src/user.ts calling api." + fn + "()";
        o.tag = demo_api_exists(fn) ? "code" : "hallucination";
      }
      break;

    case kTester:
      if (ev.kind == EventKind::Msg) {
        c.tool("run_tests");
        o.label = "tester → sandbox: run_tests";
      } else if (ev.kind == EventKind::ToolReply) {
        c.put("@tester/last_run", ev.body);
        if (starts_with(ev.body, "PASS")) {
          c.send(kReviewer, "review", ev.body);
          o.label = "tester: all tests pass → reviewer";
          o.tag = "tests_passed";
        } else {
          c.send(kCoder, "fix", ev.body);
          o.label = "tester: tests FAILED → coder";
          o.tag = "tests_failed";
        }
      }
      break;

    case kReviewer:
      if (ev.kind == EventKind::Msg && ev.topic == "review") {
        c.llm("reviewer", "ROLE reviewer\nDIFF\n" + c.file(kUserPath) + "\nTESTS\n" + ev.body);
        o.label = "reviewer → LLM: review the change";
      } else if (ev.kind == EventKind::Msg && ev.topic == "escalate") {
        c.put("sys/status", "failed");
        o.label = "reviewer: task FAILED, escalated to a human";
        o.tag = "failed";
      } else if (ev.kind == EventKind::LlmReply) {
        std::string log = c.file(kChangelogPath);
        const auto cl = ev.body.find("CHANGELOG: ");
        log += "- " + (cl != std::string::npos ? ev.body.substr(cl + 11) : std::string("change merged")) + "\n";
        c.write(kChangelogPath, log);
        c.put("sys/status", "done");
        o.label = "reviewer approves, writes CHANGELOG.md. Task complete";
        o.tag = "done";
      }
      break;

    default:
      o.label = "no handler for event";
  }
}

Kernel::StepOutput Kernel::apply(NodeRef root, std::uint32_t global_step, std::uint64_t sample, const StepInput& in,
                                 OracleSource& oracle) {
  StepOutput o;
  o.root = root;
  const std::uint64_t now_state = to_u64(store_.get_text(root, "sys/vtime").value_or("0"));
  o.vtime = now_state;

  if (in.kind == StepKind::UserEdit) {
    o.root = in.text.empty() ? store_.erase(root, in.key) : store_.put_text(root, in.key, in.text);
    o.actor = kUser;
    o.label = "user edit · " + in.key;
    o.tag = "edit";
    o.spans.push_back(Span{kUser, SpanKind::Step, false, global_step, now_state, now_state + kStepSpanUs, "user edit"});
    return o;
  }

  auto queue = load_queue(root);
  auto seq = to_u64(store_.get_text(root, "sys/seq").value_or("1"));

  if (in.kind == StepKind::Fault) {
    const std::string who(actor_name(in.actor));
    NodeRef r = store_.put_text(root, "@" + who + "/status", "dead");
    const std::uint64_t restart_at = now_state + kRestartDelayUs;
    r = store_.put_text(r, "@" + who + "/restart_at", std::to_string(restart_at));
    Event e{restart_at, seq++, in.actor, kSupervisor, EventKind::Restart, "restart", ""};
    queue.insert(std::upper_bound(queue.begin(), queue.end(), e,
                                  [](const Event& a, const Event& b) {
                                    return a.vtime != b.vtime ? a.vtime < b.vtime : a.seq < b.seq;
                                  }),
                 e);
    r = save_queue(r, queue);
    o.root = store_.put_text(r, "sys/seq", std::to_string(seq));
    o.actor = kSupervisor;
    o.label = "chaos: killed " + who + " (supervisor will restart it)";
    o.tag = "fault";
    o.spans.push_back(Span{in.actor, SpanKind::Step, false, global_step, now_state, restart_at, "✕ down"});
    return o;
  }

  if (queue.empty()) {
    o.idle = true;
    return o;
  }
  Event ev = std::move(queue.front());  // queue is kept sorted by (vtime, seq): a total order
  queue.erase(queue.begin());
  const std::string who(actor_name(ev.to));
  const std::uint64_t now = std::max(ev.vtime, now_state);

  StepCtx ctx{*this, store_, root, now, global_step, sample, oracle, o, ev, {}};
  o.actor = ev.to;

  if (ev.kind != EventKind::Restart && ctx.get("@" + who + "/status") == "dead") {
    ev.vtime = to_u64(ctx.get("@" + who + "/restart_at")) + 1;  // defer delivery until restart
    ctx.out.push_back(std::move(ev));
    o.label = who + " is down; event deferred until restart";
    o.tag = "deferred";
  } else {
    dispatch(ctx);
    o.spans.insert(o.spans.begin(),
                   Span{ev.to, SpanKind::Step, false, global_step, now, now + kStepSpanUs, who + " · " + ev.topic});
  }
  if (ctx.diverged) {
    o.idle = true;
    o.label = "replay diverged";
    return o;
  }

  for (auto& e : ctx.out) {
    e.seq = seq++;
    queue.insert(std::upper_bound(queue.begin(), queue.end(), e,
                                  [](const Event& a, const Event& b) {
                                    return a.vtime != b.vtime ? a.vtime < b.vtime : a.seq < b.seq;
                                  }),
                 std::move(e));
  }
  NodeRef r = save_queue(ctx.root, queue);
  r = store_.put_text(r, "sys/seq", std::to_string(seq));
  o.root = store_.put_text(r, "sys/vtime", std::to_string(now));
  o.vtime = now;
  return o;
}

namespace {
std::vector<std::byte> encode_step_begin(std::uint32_t g, StepKind kind, std::string_view key,
                                         std::string_view text, std::uint16_t actor) {
  Writer w;
  w.varint(g).u8(static_cast<std::uint8_t>(kind));
  if (kind == StepKind::UserEdit) w.str(key).str(text);
  if (kind == StepKind::Fault) w.varint(actor);
  return w.bytes();
}
}  // namespace

void Kernel::commit(Timeline& t, const StepInput& in, StepOutput&& out, std::uint64_t lsn_begin, double wall_us) {
  const std::uint32_t g = t.head_step() + 1;
  const Digest128 d = store_.digest(out.root);
  DigestBuilder chain(domain::kChain);
  chain.digest(t.steps.back().chain).u64(g).digest(d);
  for (std::uint64_t l = lsn_begin; l < t.log.size(); ++l) chain.u64(t.log.frame(l).header.crc32c);
  const Digest128 ch = chain.finish();

  Writer w;
  w.varint(g).digest(d).digest(ch);
  const std::uint64_t commit_lsn = t.log.append(FrameType::StepCommit, out.actor, out.vtime, w.span());

  StepRecord rec;
  rec.root = out.root;
  rec.digest = d;
  rec.chain = ch;
  rec.lsn_begin = lsn_begin;
  rec.lsn_end = commit_lsn + 1;
  rec.vtime = out.vtime;
  rec.actor = out.actor;
  rec.kind = in.kind;
  rec.tokens = out.tokens;
  rec.tokens_saved = out.tokens_saved;
  rec.wall_us = wall_us;
  rec.label = std::move(out.label);
  rec.tag = std::move(out.tag);
  if (rec.tag.empty() && out.cache_hits > 0) rec.tag = "cache_hit";
  t.steps.push_back(std::move(rec));
  for (auto& s : out.spans) t.spans.push_back(std::move(s));
  t.tokens += out.tokens;
  t.tokens_saved += out.tokens_saved;
  t.llm_calls += out.llm_calls;
  t.cache_hits += out.cache_hits;
}

bool Kernel::execute(std::uint32_t tid, const StepInput& in) {
  Timeline& t = tl(tid);
  const auto t0 = Clock::now();
  const NodeRef root = t.steps.back().root;
  if (root.empty()) return false;  // pruned history
  if (in.kind == StepKind::Dispatch && load_queue(root).empty()) return false;

  const std::uint32_t g = t.head_step() + 1;
  const std::uint64_t lsn_begin = t.log.append(FrameType::StepBegin, 0, t.steps.back().vtime,
                                               encode_step_begin(g, in.kind, in.key, in.text, in.actor));
  LiveOracle oracle(*this);
  StepOutput out = apply(root, g, t.sample, in, oracle);
  for (std::size_t i = 0; i < oracle.frames.size(); ++i)
    t.log.append(oracle.frames[i].first, oracle.frame_actors[i], out.vtime, oracle.frames[i].second);
  const double wall = us_since(t0);
  commit(t, in, std::move(out), lsn_begin, wall);
  metrics_.total_step_us += wall;
  metrics_.steps_executed += 1;
  return true;
}

bool Kernel::step(std::uint32_t tid) { return execute(tid, StepInput{StepKind::Dispatch, {}, {}, 0}); }

std::uint32_t Kernel::run(std::uint32_t tid, std::uint32_t max_steps) {
  std::uint32_t n = 0;
  while (n < max_steps && step(tid)) ++n;
  return n;
}

void Kernel::inject(std::uint32_t tid, std::string_view key, std::string_view text) {
  execute(tid, StepInput{StepKind::UserEdit, std::string(key), std::string(text), 0});
}

void Kernel::kill(std::uint32_t tid, std::uint16_t actor) {
  if (actor < kPlanner || actor > kReviewer) throw std::invalid_argument("khonsu: cannot kill that actor");
  execute(tid, StepInput{StepKind::Fault, {}, {}, actor});
}

std::uint32_t Kernel::fork(std::uint32_t tid, std::uint32_t g, std::string name, std::optional<std::uint64_t> sample) {
  const auto t0 = Clock::now();
  const StepRecord& at = record_at(tid, g);
  if (at.root.empty()) throw std::invalid_argument("khonsu: cannot fork a pruned step");

  auto c = std::make_unique<Timeline>();
  c->id = static_cast<std::uint32_t>(timelines_.size());
  c->parent = static_cast<std::int32_t>(tid);
  c->base_step = g;
  c->sample = sample.value_or(timelines_[tid]->sample);
  if (name.empty()) {
    name = c->id < 26 ? std::string(1, static_cast<char>('A' + c->id)) : "T" + std::to_string(c->id);
  }
  c->name = std::move(name);

  Writer w;
  w.varint(tid).varint(g).digest(at.digest).varint(c->sample);
  c->log.append(FrameType::Fork, kUser, at.vtime, w.span());

  StepRecord base;
  base.root = at.root;  // ← the entire fork: one 4-byte handle, zero nodes or pages copied
  base.digest = at.digest;
  base.chain = at.chain;
  base.lsn_begin = 0;
  base.lsn_end = 1;
  base.vtime = at.vtime;
  base.actor = kUser;
  base.kind = StepKind::Genesis;
  base.label = "fork of " + timelines_[tid]->name + " @ step " + std::to_string(g);
  base.tag = "fork";
  c->steps.push_back(std::move(base));
  timelines_.push_back(std::move(c));
  metrics_.last_fork_us = us_since(t0);
  return timelines_.back()->id;
}

std::vector<std::uint32_t> Kernel::speculate(std::uint32_t tid, std::uint32_t g, std::uint32_t n,
                                             std::uint32_t max_steps) {
  struct Scored {
    std::uint32_t id;
    double score;
  };
  std::vector<Scored> scored;
  for (std::uint32_t i = 0; i < n; ++i) {
    const std::uint32_t c =
        fork(tid, g, "spec-" + std::to_string(i + 1), splitmix64(timelines_[tid]->sample * 1000003u + i + 1));
    run(c, max_steps);
    const Timeline& t = timeline(c);
    const std::string st = status(c);
    // Evaluator: success dominates; then prefer less virtual time and fewer tokens.
    double score = st == "done" ? 1000.0 : (st == "failed" ? 0.0 : 100.0);
    score -= static_cast<double>(t.steps.back().vtime) / 1e6;
    score -= static_cast<double>(t.tokens) / 1e4;
    scored.push_back({c, score});
  }
  std::stable_sort(scored.begin(), scored.end(), [](const Scored& a, const Scored& b) { return a.score > b.score; });
  std::vector<std::uint32_t> ids;
  for (std::size_t i = 0; i < scored.size(); ++i) {
    ids.push_back(scored[i].id);
    if (i > 0) tl(scored[i].id).pruned = true;
  }
  return ids;
}

