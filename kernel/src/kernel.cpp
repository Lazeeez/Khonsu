std::string generated_client() {
  std::string s =
      "// AUTO-GENERATED by openapi-gen 7.3 - do not edit by hand.\n"
      "// Endpoint registry for the demo service. One page of this file is patched in place.\n\n";
  static constexpr const char* kMethods[] = {"GET", "POST", "PUT"};
  char buf[160];
  for (int i = 0; i < 520; ++i) {
    if (i == 260)
      s += "export const USER_LOOKUP_FN = \"" + pad("UNSET", kPatchWidth) + "\"; // @khonsu:patch-site\n";
    std::snprintf(buf, sizeof buf,
                  "export const endpoint_%04d = { path: \"/v1/resource/%04d\", method: \"%s\", timeoutMs: %d };\n", i,
                  i, kMethods[i % 3], 1000 + (i * 37) % 4000);
    s += buf;
  }
  return s;
}

