Kernel::Kernel(std::uint64_t entropy_seed, std::unique_ptr<LanguageModel> model)
    : model_(model ? std::move(model) : std::make_unique<SimulatedModel>()), entropy_(entropy_seed) {}

Kernel::~Kernel() = default;

std::vector<Event> Kernel::load_queue(NodeRef root) const {
  std::vector<Event> q;
  const auto blob = store_.get_text(root, "sys/queue");
  if (!blob) return q;
  Reader rd(as_bytes(*blob));
  const auto n = rd.varint();
  q.reserve(static_cast<std::size_t>(n));
  for (std::uint64_t i = 0; i < n && rd.ok(); ++i) {
    Event e;
    e.vtime = rd.varint();
    e.seq = rd.varint();
    e.to = static_cast<std::uint16_t>(rd.varint());
    e.from = static_cast<std::uint16_t>(rd.varint());
    e.kind = static_cast<EventKind>(rd.u8());
    e.topic = std::string(rd.str());
    e.body = std::string(rd.str());
    q.push_back(std::move(e));
  }
  return q;
}

NodeRef Kernel::save_queue(NodeRef root, const std::vector<Event>& q) {
  Writer w;
  w.varint(q.size());
  for (const auto& e : q)
    w.varint(e.vtime).varint(e.seq).varint(e.to).varint(e.from).u8(static_cast<std::uint8_t>(e.kind)).str(e.topic).str(
        e.body);
  const auto& b = w.bytes();
  return store_.put_text(root, "sys/queue", std::string_view(reinterpret_cast<const char*>(b.data()), b.size()));
}

std::vector<Event> Kernel::pending(NodeRef root) const { return load_queue(root); }

std::uint32_t Kernel::load_scenario(std::string_view name) {
  if (name != "issue-42") throw std::invalid_argument("khonsu: unknown scenario");
  scenario_ = std::string(name);
  scenario_seed_ = 42;

  NodeRef r = kEmpty;
  r = store_.put_file(r, kIssuePath, kIssue);
  r = store_.put_file(r, kDocsPath, kDocs);
  r = store_.put_file(r, kApiPath, kApi);
  r = store_.put_file(r, kUserPath, kUserStub);
  r = store_.put_file(r, kTestPath, kTest);
  r = store_.put_file(r, kClientPath, generated_client());
  r = store_.put_file(r, "/repo/package.json",
                      "{\n  \"name\": \"demo-service\",\n  \"scripts\": { \"test\": \"vitest run\" }\n}\n");
  r = store_.put_text(r, "sys/status", "running");
  r = store_.put_text(r, "sys/seq", "1");
  r = store_.put_text(r, "sys/vtime", "0");
  r = store_.put_text(r, "sys/tokens", "0");
  r = store_.put_text(r, "sys/gas", "0");
  for (std::uint16_t a = kPlanner; a <= kReviewer; ++a)
    r = store_.put_text(r, "@" + std::string(actor_name(a)) + "/status", "alive");
  r = save_queue(r, {Event{0, 0, kPlanner, kUser, EventKind::Start, "start", "Resolve issue #42"}});

  auto t = std::make_unique<Timeline>();
  t->id = static_cast<std::uint32_t>(timelines_.size());
  t->name = "main";
  const Digest128 d = store_.digest(r);
  Writer w;
  w.str(scenario_).varint(scenario_seed_).digest(d);
  t->log.append(FrameType::Genesis, kUser, 0, w.span());
  StepRecord g;
  g.root = r;
  g.digest = d;
  DigestBuilder chain(domain::kChain);
  chain.digest(d).u64(t->log.frame(0).header.crc32c);
  g.chain = chain.finish();
  g.lsn_begin = 0;
  g.lsn_end = 1;
  g.kind = StepKind::Genesis;
  g.label = "genesis · scenario " + scenario_;
  g.tag = "genesis";
  t->steps.push_back(std::move(g));
  timelines_.push_back(std::move(t));
  return timelines_.back()->id;
}

NodeRef Kernel::root_at(std::uint32_t tid, std::uint32_t g) const { return record_at(tid, g).root; }

const StepRecord& Kernel::record_at(std::uint32_t tid, std::uint32_t g) const {
  const Timeline* t = timelines_.at(tid).get();
  while (g < t->base_step) {
    if (t->parent < 0) throw std::out_of_range("khonsu: step before genesis");
    t = timelines_.at(static_cast<std::size_t>(t->parent)).get();
  }
  const std::size_t i = g - t->base_step;
  if (i >= t->steps.size()) throw std::out_of_range("khonsu: step beyond head");
  return t->steps[i];
}

std::string Kernel::status(std::uint32_t tid) const {
  const auto s = store_.get_text(timeline(tid).steps.back().root, "sys/status");
  return s ? std::string(*s) : "running";
}

