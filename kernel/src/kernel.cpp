std::uint32_t Kernel::import_log(std::span<const std::byte> bytes, std::string* error) {
  auto set_err = [&](std::string e) {
    if (error) *error = std::move(e);
  };
  RecoveryReport rr;
  const EventLog src = EventLog::parse(bytes, &rr);
  if (src.size() == 0 || src.frame(0).header.type != FrameType::Genesis) {
    set_err("not a genesis-rooted Khonsu log (" + rr.reason + ")");
    return UINT32_MAX;
  }
  Reader gr(src.frame(0).payload);
  const std::string scenario(gr.str());
  gr.varint();
  const Digest128 genesis = gr.digest();
  const std::uint32_t tid = load_scenario(scenario);
  if (store_.digest(timeline(tid).steps[0].root) != genesis) {
    set_err("genesis digest mismatch (different scenario version)");
    return tid;
  }
  tl(tid).name = "imported";

  std::uint64_t l = 1;
  while (l < src.size()) {
    if (src.frame(l).header.type != FrameType::StepBegin) break;
    std::uint64_t end = l + 1;
    while (end < src.size() && src.frame(end).header.type != FrameType::StepCommit) ++end;
    if (end >= src.size()) break;  // torn final step: ignore, like WAL recovery
    const auto sb = decode_step_begin(src.frame(l).payload);
    Timeline& t = tl(tid);
    const auto t0 = Clock::now();
    const std::uint64_t lsn_begin = t.log.append(FrameType::StepBegin, 0, t.steps.back().vtime, src.frame(l).payload);
    ReplayOracle oracle(src, l + 1, end);
    StepOutput out = apply(t.steps.back().root, sb.global, t.sample, StepInput{sb.kind, sb.key, sb.text, sb.actor}, oracle);
    if (!oracle.error.empty()) {
      set_err("replay diverged at step " + std::to_string(sb.global) + ": " + oracle.error);
      return tid;
    }
    for (const auto& [h, r] : oracle.responses) cache_.emplace(h, r);  // recorded answers feed the cache
    for (std::size_t i = 0; i < oracle.frames.size(); ++i)
      t.log.append(oracle.frames[i].first, oracle.frame_actors[i], out.vtime, oracle.frames[i].second);
    Reader cr(src.frame(end).payload);
    cr.varint();
    const Digest128 recorded = cr.digest();
    commit(t, StepInput{sb.kind, sb.key, sb.text, sb.actor}, std::move(out), lsn_begin, us_since(t0));
    if (t.steps.back().digest != recorded) {
      set_err("state digest mismatch at step " + std::to_string(sb.global));
      return tid;
    }
    l = end + 1;
  }
  return tid;
}

