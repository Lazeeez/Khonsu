namespace {
struct StepBeginDecoded {
  std::uint32_t global = 0;
  StepKind kind = StepKind::Dispatch;
  std::string key, text;
  std::uint16_t actor = 0;
  bool ok = false;
};

StepBeginDecoded decode_step_begin(std::span<const std::byte> p) {
  Reader rd(p);
  StepBeginDecoded d;
  d.global = static_cast<std::uint32_t>(rd.varint());
  d.kind = static_cast<StepKind>(rd.u8());
  if (d.kind == StepKind::UserEdit) {
    d.key = std::string(rd.str());
    d.text = std::string(rd.str());
  }
  if (d.kind == StepKind::Fault) d.actor = static_cast<std::uint16_t>(rd.varint());
  d.ok = rd.ok();
  return d;
}
}  // namespace

VerifyReport Kernel::verify(std::uint32_t tid) {
  const auto t0 = Clock::now();
  VerifyReport rep;
  const Timeline& t = timeline(tid);
  NodeRef root = t.steps.front().root;
  Digest128 chain = t.steps.front().chain;
  auto fail = [&](std::uint32_t g, std::string why) {
    rep.ok = false;
    rep.first_divergent_step = g;
    rep.reason = std::move(why);
  };

  for (std::size_t i = 1; i < t.steps.size() && rep.ok; ++i) {
    const StepRecord& rec = t.steps[i];
    const std::uint32_t g = t.base_step + static_cast<std::uint32_t>(i);
    for (std::uint64_t l = rec.lsn_begin; l < rec.lsn_end; ++l) {
      if (!t.log.verify(l)) {
        fail(g, "CRC32C mismatch in " + std::string(frame_type_name(t.log.frame(l).header.type)) + " frame (lsn " +
                    std::to_string(l) + "): the log is corrupt");
        break;
      }
    }
    if (!rep.ok) break;
    const auto sb = decode_step_begin(t.log.frame(rec.lsn_begin).payload);
    if (!sb.ok || sb.global != g) {
      fail(g, "malformed StepBegin frame");
      break;
    }
    ReplayOracle oracle(t.log, rec.lsn_begin + 1, rec.lsn_end - 1);
    StepOutput out = apply(root, g, t.sample, StepInput{sb.kind, sb.key, sb.text, sb.actor}, oracle);
    if (!oracle.error.empty()) {
      fail(g, oracle.error);
      break;
    }
    if (!oracle.exhausted()) {
      fail(g, "recording has oracle calls the agent no longer makes");
      break;
    }
    Reader cr(t.log.frame(rec.lsn_end - 1).payload);
    cr.varint();
    const Digest128 recorded = cr.digest();
    const Digest128 recorded_chain = cr.digest();
    const Digest128 replayed = store_.digest(out.root);
    if (replayed != recorded) {
      rep.diff = store_.diff(rec.root, out.root);
      fail(g, "state digest mismatch: recorded " + recorded.short_hex() + ", replay produced " + replayed.short_hex());
      break;
    }
    DigestBuilder cb(domain::kChain);
    cb.digest(chain).u64(g).digest(replayed);
    for (std::uint64_t l = rec.lsn_begin; l + 1 < rec.lsn_end; ++l) cb.u64(t.log.frame(l).header.crc32c);
    chain = cb.finish();
    if (chain != recorded_chain) {
      fail(g, "hash-chain mismatch: log history was rewritten");
      break;
    }
    root = out.root;
    ++rep.steps_checked;
  }
  rep.ms = us_since(t0) / 1000.0;
  metrics_.last_verify_ms = rep.ms;
  metrics_.last_verify_steps = rep.steps_checked;
  return rep;
}

bool Kernel::tamper_oracle(std::uint32_t tid, std::uint32_t g) {
  Timeline& t = tl(tid);
  if (g <= t.base_step || g > t.head_step()) return false;
  const StepRecord& rec = t.steps[g - t.base_step];
  for (std::uint64_t l = rec.lsn_begin; l < rec.lsn_end; ++l) {
    const auto f = t.log.frame(l);
    if (f.header.type == FrameType::OracleResponse && f.header.payload_len > 4) {
      t.log.tamper_for_test(l, f.header.payload_len - 2);  // edit the response text, recompute CRC
      return true;
    }
  }
  return false;
}

bool Kernel::corrupt_frame(std::uint32_t tid, std::uint32_t g) {
  Timeline& t = tl(tid);
  if (g <= t.base_step || g > t.head_step()) return false;
  const StepRecord& rec = t.steps[g - t.base_step];
  t.log.corrupt_for_test(rec.lsn_end - 1, 3);  // StepCommit frame; CRC left stale
  return true;
}

